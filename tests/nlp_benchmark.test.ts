interface Passage {
  title: string;
  category: string;
  text: string;
  charLength: number;
}

function buildPassage(title: string, category: string, paragraphs: string[]): Passage {
  const fullText = paragraphs.join('\n\n');
  return {
    title,
    category,
    text: fullText,
    charLength: fullText.length,
  };
}

