describe('50개 이상 1,000자 대형 한국어 예문 실전 스트레스 및 애매한 문장 분석 테스트', () => {
  const passages = generate52Passages();

  it('50개 이상의 예문이 모두 1,000자 이상으로 구성되어 있다', () => {
    expect(passages.length).toBeGreaterThanOrEqual(50);
    passages.forEach((p, idx) => {
      if (p.charLength < 1000) {
        console.log(`[Under 1000] #${idx + 1} "${p.title}": ${p.charLength} chars`);
      }
      expect(p.charLength).toBeGreaterThanOrEqual(1000);
    });
  });

  it('50개 이상의 예문 전체에서 크래시, 글자 누락, 문단 파괴 없이 100% 정상 분리 및 조립된다', () => {
    let totalSentences = 0;
    const ambiguousCases: Array<{
      passage: string;
      sentenceNo: number;
      type: string;
      sentenceText: string;
    }> = [];

    passages.forEach((p, idx) => {
      resetSentenceCounter(1);
      const cards = splitIntoSentenceCards(p.text);
      expect(cards.length).toBeGreaterThan(0);
      totalSentences += cards.length;

      // Check text integrity: no character dropped
      const assembled = assembleDraft(cards);
      expect(assembled.replace(/\s/g, '')).toBe(p.text.replace(/\s/g, ''));

      // Scan for ambiguous / tricky sentence boundary cases
      cards.forEach((card, sIdx) => {
        const text = card.currentText.trim();

        if (/["'』」][이가은는을를에와과의로]|["'』」]라고|["'』」]하며|["'』」]라는/.test(text)) {
          ambiguousCases.push({
            passage: p.title,
            sentenceNo: sIdx + 1,
            type: '인용부호 뒤 조사/어미 결합 ("..."라고 / "..."라는)',
            sentenceText: text,
          });
        }
        if (/\d+\.\d+/.test(text)) {
          ambiguousCases.push({
            passage: p.title,
            sentenceNo: sIdx + 1,
            type: '소수점 수치 포함 (3.14% / 24.8% 등)',
            sentenceText: text,
          });
        }
        if (/\.{2,}/.test(text)) {
          ambiguousCases.push({
            passage: p.title,
            sentenceNo: sIdx + 1,
            type: '말줄임표(...) 포함 문장',
            sentenceText: text,
          });
        }
        if (/\([^)]*\.[^)]*\)/.test(text)) {
          ambiguousCases.push({
            passage: p.title,
            sentenceNo: sIdx + 1,
            type: '괄호 내부 마침표 포함 문장',
            sentenceText: text,
          });
        }
      });
    });

    console.log(`\n======================================================`);
    console.log(`[검증 통계] 총 검증 예문: ${passages.length}개 (전체 1,000자 이상)`);
    console.log(`[검증 통계] 총 추출 문장 카드: ${totalSentences}개`);
    console.log(`[검증 통계] 글자 누락 및 시스템 크래시: 0건 (100% 무결성 통과)`);
    console.log(`[검증 통계] 추출된 애매한/주의 문장 케이스: ${ambiguousCases.length}건`);
    console.log(`======================================================\n`);

    // Print first 15 representative ambiguous sentences for user review
    console.log('▼ 사용자가 직접 판단할 수 있는 대표적인 애매한 문장 분리 결과 샘플:');
    ambiguousCases.slice(0, 15).forEach((item, i) => {
      console.log(`\n[사례 ${i + 1}] (${item.passage}) 문장 #${item.sentenceNo}`);
      console.log(`▶ 특징: ${item.type}`);
      console.log(`▶ 분리 결과: "${item.sentenceText}"`);
    });
  });
});
